def write_png(path, rows):
    h, w = len(rows), len(rows[0])
    raw = b"".join(b"\x00" + bytes(c for px in row for c in px) for row in rows)

    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    png = (b"\x89PNG\r\n\x1a\n"
           + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(raw, 9))
           + chunk(b"IEND", b""))
    path.write_bytes(png)


def render(name, grid):
    lines = grid.strip().splitlines()
    widths = {len(line) for line in lines}
    if len(widths) != 1:
        raise ValueError(f"{name}: rows have different widths {sorted(widths)}")
    rows = []
    for line in lines:
        row = [PALETTE[ch] for ch in line for _ in range(SCALE)]
        rows.extend([row] * SCALE)
    return rows


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, grid in SPRITES.items():
        write_png(OUT / f"{name}.png", render(name, grid))
    meta = {
        "name": "Clawd",
        "pixelArt": True,
        "anchor": [0.5, 0.0],
        "height": 3.0,
        "facing": "right",
        "sprites": {name: f"{name}.png" for name in SPRITES},
    }
    (OUT / "character.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"wrote {len(SPRITES)} sprites to {OUT}")


if __name__ == "__main__":
    main()
